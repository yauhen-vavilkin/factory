package org.folio.factory.devfactory.runtime;

import org.folio.factory.devfactory.candidate.Candidate;
import tools.jackson.databind.json.JsonMapper;

import java.nio.ByteBuffer;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Optional;

/**
 * The yarn.lock that the trusted starting build generated for a module without one. It is an
 * artifact of the execution, never part of a candidate patch, so every stage installs the same
 * dependency versions. {@code packageJsonBlob} is the Git blob id of the package.json it was
 * generated for: a candidate with that same blob can be installed frozen.
 */
public record PinnedLockfile(String sha256, String content, String packageJsonBlob) {
    public static final String FILE = "yarn.lock";
    public static final int MAX_BYTES = 4 * 1024 * 1024;
    private static final String HEADER = "# yarn lockfile v1";
    private static final JsonMapper JSON = JsonMapper.builder().build();

    public PinnedLockfile {
        // Yarn writes "# THIS IS AN AUTOGENERATED FILE…" first and the version marker on the next lines.
        if (content == null || content.lines().limit(5).noneMatch(HEADER::equals)
                || content.getBytes(StandardCharsets.UTF_8).length > MAX_BYTES)
            throw new IllegalArgumentException("Not a usable yarn lockfile");
        if (!Candidate.sha256(content).equals(sha256))
            throw new IllegalArgumentException("Lockfile digest mismatch");
        if (packageJsonBlob != null && !packageJsonBlob.isEmpty() && !packageJsonBlob.matches("[a-f0-9]{40}"))
            throw new IllegalArgumentException("Invalid package.json blob id");
        packageJsonBlob = packageJsonBlob == null ? "" : packageJsonBlob;
    }

    /** Validates what yarn left in the workspace; the package.json blob is attached with {@link #forPackageJson}. */
    public static PinnedLockfile of(byte[] bytes) {
        if (bytes.length > MAX_BYTES)
            throw new IllegalArgumentException("yarn.lock exceeds " + MAX_BYTES / (1024 * 1024) + " MiB");
        String text;
        try {
            text = StandardCharsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT).decode(ByteBuffer.wrap(bytes)).toString();
        } catch (CharacterCodingException e) {
            throw new IllegalArgumentException("yarn.lock is not UTF-8 text");
        }
        return new PinnedLockfile(Candidate.sha256(text), text, "");
    }

    /**
     * The one rule for installing against this pin: frozen while the checkout's package.json is the one the
     * lockfile was generated for, otherwise a plain install that keeps the pins and resolves only what is new.
     */
    public InstallMode installMode(java.nio.file.Path checkout) {
        return packageJsonBlob.equals(org.folio.factory.devfactory.candidate.CandidateFreezer.trackedBlob(checkout, "package.json"))
                ? InstallMode.FROZEN : InstallMode.RESOLVE;
    }

    public PinnedLockfile forPackageJson(String blob) {
        return new PinnedLockfile(sha256, content, blob);
    }

    /** The {@code dev_lockfile.json} artifact. */
    public String toArtifact() {
        var artifact = new LinkedHashMap<String, Object>();
        artifact.put("state", "PINNED");
        artifact.put("sha256", sha256);
        artifact.put("packageJsonBlob", packageJsonBlob);
        artifact.put("content", content);
        return JSON.writeValueAsString(artifact);
    }

    /** A lockfile artifact that carries nothing to seed; {@code state} is NOT_NEEDED or NOT_RUN. */
    public static String none(String state, String reason) {
        return JSON.writeValueAsString(Map.of("state", state, "reason", reason));
    }

    /** Empty for any artifact that is not a pinned lockfile; a pinned one must verify its own digest. */
    public static Optional<PinnedLockfile> parse(String artifact) {
        if (artifact == null || artifact.isBlank()) return Optional.empty();
        var node = JSON.readTree(artifact);
        if (!"PINNED".equals(node.path("state").asString(""))) return Optional.empty();
        return Optional.of(new PinnedLockfile(node.path("sha256").asString(""), node.path("content").asString(""),
                node.path("packageJsonBlob").asString("")));
    }
}

package org.folio.factory.devfactory.runtime;

import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class PinnedLockfileTest {
    private static final String LOCK = "# yarn lockfile v1\n\n\nleft-pad@^1.3.0:\n  version \"1.3.0\"\n";

    @Test
    void artifactRoundTripKeepsTheContentDigestAndPackageJsonBlob() {
        var pinned = PinnedLockfile.of(LOCK.getBytes(StandardCharsets.UTF_8)).forPackageJson("a".repeat(40));

        var parsed = PinnedLockfile.parse(pinned.toArtifact()).orElseThrow();

        assertThat(parsed).isEqualTo(pinned);
        assertThat(parsed.content()).isEqualTo(LOCK);
        assertThat(parsed.packageJsonBlob()).isEqualTo("a".repeat(40));
    }

    @Test
    void theHeaderYarnActuallyWritesIsAccepted() {
        var real = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\nleft-pad@^1.3.0:\n";

        assertThat(PinnedLockfile.of(real.getBytes(StandardCharsets.UTF_8)).content()).isEqualTo(real);
        assertThatThrownBy(() -> PinnedLockfile.of("# some other tool\n# yarn lockfile v2\n".getBytes(StandardCharsets.UTF_8)))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void artifactsWithoutAPinnedLockfileParseToEmpty() {
        assertThat(PinnedLockfile.parse(PinnedLockfile.none("NOT_NEEDED", "No lockfile to pin"))).isEmpty();
        assertThat(PinnedLockfile.parse(PinnedLockfile.none("NOT_RUN", "x"))).isEmpty();
        assertThat(PinnedLockfile.parse("{}")).isEmpty();
        assertThat(PinnedLockfile.parse(null)).isEmpty();
        assertThat(PinnedLockfile.parse("")).isEmpty();
    }

    @Test
    void anArtifactWhoseContentWasAlteredIsRejected() {
        String artifact = PinnedLockfile.of(LOCK.getBytes(StandardCharsets.UTF_8)).toArtifact()
                .replace("1.3.0\\\"", "9.9.9\\\"");

        assertThat(artifact).contains("9.9.9");
        assertThatThrownBy(() -> PinnedLockfile.parse(artifact)).isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("digest");
    }

    @Test
    void onlyYarnLockfilesWithinTheSizeLimitAreAccepted() {
        assertThatThrownBy(() -> PinnedLockfile.of("{\"not\":\"a lockfile\"}".getBytes(StandardCharsets.UTF_8)))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("Not a usable yarn lockfile");
        assertThatThrownBy(() -> PinnedLockfile.of(new byte[]{'#', ' ', (byte) 0xC3, (byte) 0x28}))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("UTF-8");
        var big = ("# yarn lockfile v1\n" + "x".repeat(PinnedLockfile.MAX_BYTES)).getBytes(StandardCharsets.UTF_8);
        assertThatThrownBy(() -> PinnedLockfile.of(big)).isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("exceeds");
    }

    @Test
    void installModeIsFrozenOnlyWhileTheCheckoutKeepsThePinnedPackageJson(@org.junit.jupiter.api.io.TempDir java.nio.file.Path checkout)
            throws Exception {
        org.folio.factory.devfactory.candidate.CandidateFreezer.git(checkout, "init", "--quiet");
        java.nio.file.Files.writeString(checkout.resolve("package.json"), "{\"name\":\"a\"}");
        org.folio.factory.devfactory.candidate.CandidateFreezer.git(checkout, "add", "package.json");
        var blob = org.folio.factory.devfactory.candidate.CandidateFreezer.trackedBlob(checkout, "package.json");
        var pin = PinnedLockfile.of(LOCK.getBytes(StandardCharsets.UTF_8)).forPackageJson(blob);

        assertThat(pin.installMode(checkout)).isEqualTo(InstallMode.FROZEN);

        java.nio.file.Files.writeString(checkout.resolve("package.json"), "{\"name\":\"a\",\"dependencies\":{\"x\":\"1\"}}");
        org.folio.factory.devfactory.candidate.CandidateFreezer.git(checkout, "add", "package.json");
        assertThat(pin.installMode(checkout)).isEqualTo(InstallMode.RESOLVE);
    }

    @Test
    void packageJsonBlobMustBeAGitObjectIdOrEmpty() {
        var pinned = PinnedLockfile.of(LOCK.getBytes(StandardCharsets.UTF_8));

        assertThat(pinned.forPackageJson("").packageJsonBlob()).isEmpty();
        assertThatThrownBy(() -> pinned.forPackageJson("not-a-sha")).isInstanceOf(IllegalArgumentException.class);
    }
}
